import { test } from 'node:test';
import assert from 'node:assert/strict';
import { GameController } from '../src/ui/controller.ts';
import { startGame } from '../src/game/start.ts';

test('deferred controller has no offline match until an explicit start', () => {
  let starts = 0;
  const ui = new GameController(() => { starts++; return startGame(); }, { startImmediately: false });
  assert.equal(starts, 0);
  assert.equal(ui.hasGame, false);
  ui.newGame('tonnan');
  assert.equal(starts, 1);
  assert.equal(ui.hasGame, true);
  assert.equal(ui.match.format, 'tonnan');
  ui.clearGame();
  assert.equal(ui.hasGame, false);
});

test('selection toggles by physical ID without changing game; confirmation is single-use and reset is fresh', () => {
  const ui = new GameController();
  const game = ui.game;
  const snapshot = structuredClone(game);
  const [a, b] = game.players[0].hand;
  assert.equal(ui.canConfirm, false);
  ui.confirm();
  ui.select('missing');
  assert.equal(ui.selectedTileId, null);
  ui.select(a.id);
  assert.equal(ui.canConfirm, true);
  ui.select(b.id);
  assert.equal(ui.selectedTileId, b.id);
  ui.select(b.id);
  assert.equal(ui.selectedTileId, null);
  assert.equal(ui.canConfirm, false);
  assert.equal(ui.game, game);
  assert.deepEqual(ui.game, snapshot);
  ui.select(a.id);
  ui.confirm();
  assert.equal(ui.game.players[0].discardHistory[0], a);
  assert.equal(ui.game.players[0].hand.length, 13);
  assert.equal(ui.selectedTileId, null);
  assert.equal(ui.canConfirm, false);
  const stopped = ui.game;
  ui.select(b.id);
  ui.confirm();
  assert.equal(ui.game, stopped);
  ui.newGame();
  assert.notEqual(ui.game, game);
  assert.equal(ui.selectedTileId, null);
  assert.equal(ui.canConfirm, false);
  assert.equal(ui.game.phase, 'awaiting-discard');
  assert.ok(ui.game.players.every(p => p.river.length === 0));
  assert.equal(ui.game.players[0].hand.length, 13);
  assert.ok(ui.game.players[0].drawnTile);
});
